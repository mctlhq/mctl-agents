"""Render the Telegram digest, spike-draft URLs and the footer."""
from __future__ import annotations

import html
import json
from dataclasses import dataclass, field
from typing import Any
from urllib.parse import urlencode

from orchestrator.scout.feeds import SourceResult

MAX_BUTTON_URL_CHARS = 2000
MAX_MESSAGE_CHARS = 4096
# Telegram rejects the whole message ("reply markup is too long") past an undocumented
# total keyboard size; 10 full structured drafts (~1.8k chars each) crossed it on
# 2026-10-30 while ~1k-char drafts never did. Measured as serialized JSON.
MAX_MARKUP_CHARS = 9000


# Static, compact scaffold: the button URL carries the body, so prose size is budgeted
# (see tests/test_scout.py::test_draft_url_worst_case_fields_fit).
SPIKE_SECTIONS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("Existing / duplicate check",
     ("Verify Related against current issues/code; reuse an existing owner, no parity-only capability.",)),
    ("Required experiment",
     ("Smallest bounded experiment that can falsify the question, on current MCTL workload, not vendor claims.",)),
    ("Measurements",
     ("Baseline vs candidate: success, cost, latency, reliability. unknown is not zero.",)),
    ("Invariants",
     ("No rollout or authority expansion; identity/policy/approval boundaries stay authoritative.",)),
    ("Deliverables",
     ("Duplicate map, experiment evidence, follow-ups for proven gaps, one recommendation from Outcomes.",)),
    ("Non-goals",
     ("Implementation before the decision; new epic/runtime for parity only.",)),
)
REQUIRED_SECTIONS = tuple(h for h, _ in SPIKE_SECTIONS)


@dataclass
class Scored:
    id: str
    title: str
    link: str
    source: str
    repo: str
    score: float
    question: str
    outcomes: str
    pitch_ru: str
    why_en: str
    related: list[str] = field(default_factory=list)
    adds_to: bool = False
    urgency: int = 0


@dataclass
class Counts:
    fetched: int = 0
    in_window: int = 0
    deduped: int = 0
    relevant: int = 0
    scored: int = 0
    unscored: int = 0
    unscored_budget: int = 0
    undated: int = 0
    dedupe_unavailable: bool = False
    backlog_unavailable: bool = False


def draft_body(item: Scored, run_id: str, scaffold: bool = True) -> str:
    related = ", ".join(item.related) if item.related else "none"
    sections = "".join(
        f"\n\n## {heading}" + "".join(f"\n- {b}" for b in bullets) for heading, bullets in SPIKE_SECTIONS
    ) if scaffold else ""
    return (
        f"Source: {item.link}\n"
        f"Question: {item.question}\n"
        f"Outcomes: {item.outcomes}\n"
        f"Lifecycle: proposed\n"
        f"Related: {related}\n"
        f"Why mctl: {item.why_en}"
        f"{sections}\n\n"
        f"Generated by mctl-agents scout, run {run_id}."
    )


def _url(repo: str, title: str, body: str) -> str:
    # spike.yml is the issue form in each target repo (and the org default); it adds
    # agents:intake, and its field id "body" is what the body parameter prefills.
    q = urlencode({"template": "spike.yml", "title": title, "body": body, "labels": "spike:scout"})
    return f"https://github.com/mctlhq/{repo}/issues/new?{q}"


def draft_url(item: Scored, run_id: str, scaffold: bool = True) -> tuple[str, str | None]:
    """Return (url, full_body_if_fallback). Fallback uses the short body."""
    title = f"spike: {item.question}"
    body = draft_body(item, run_id, scaffold)
    url = _url(item.repo, title, body)
    if len(url) <= MAX_BUTTON_URL_CHARS:
        return url, None
    return source_only_url(item), body


def source_only_url(item: Scored) -> str:
    title = f"spike: {item.question}"
    short = _url(item.repo, title, f"Source: {item.link}")
    if len(short) > MAX_BUTTON_URL_CHARS:
        short = _url(item.repo, title[:120], f"Source: {item.link}")
    return short


def _row(n: int, url: str) -> list[dict[str, str]]:
    # mctl-agent's scout:create:N callback reads the draft back from the URL
    # button in the same row (mctl-agent internal/scoutspike), so both must
    # stay together and keep these exact texts.
    return [{"text": f"Draft spike {n}", "url": url},
            {"text": f"Create spike {n}", "callback_data": f"scout:create:{n}"}]


def markup_size(rows: list[list[dict[str, str]]]) -> int:
    return len(json.dumps({"inline_keyboard": rows}))


def build_keyboard(items: list[Scored], run_id: str) -> tuple[list[list[dict[str, str]]], list[tuple[int, str]]]:
    """Rows for items within MAX_MARKUP_CHARS, plus (n, full_body) for drafts cut by the URL cap.

    Higher-ranked items keep the richest draft that still leaves room for every
    later item at its smallest (Source-only) form. A draft dropped only for the
    keyboard budget gets no reply: "Create spike" builds the issue from the URL.
    """
    floor = [_row(n, source_only_url(it)) for n, it in enumerate(items, 1)]
    rows: list[list[dict[str, str]]] = []
    fallbacks: list[tuple[int, str]] = []
    for n, it in enumerate(items, 1):
        rest = floor[n:]
        chosen = floor[n - 1]
        for scaffold in (True, False):
            url, full = draft_url(it, run_id, scaffold)
            if markup_size([*rows, _row(n, url), *rest]) <= MAX_MARKUP_CHARS:
                chosen = _row(n, url)
                if full and scaffold:
                    fallbacks.append((n, f"Draft {n}:\n{html.escape(full)}"))
                break
        rows.append(chosen)
    return rows, fallbacks


def render_footer(results: list[SourceResult], c: Counts) -> str:
    # One line per source outgrew the 4096-char message and pushed items out, so
    # healthy sources are a count and only the ones needing attention are listed.
    ok = sum(r.status == "ok" for r in results)
    disabled = [r.name for r in results if r.status == "disabled"]
    lines = [f"sources: {ok} ok" + (f", {len(disabled)} disabled" if disabled else "")]
    lines += [f"{html.escape(r.name)}: {html.escape(r.label())}" for r in results
              if r.status not in ("ok", "disabled")]
    if disabled:
        lines.append("disabled: " + html.escape(", ".join(disabled)))
    lines.append(
        f"fetched {c.fetched} | in window {c.in_window} | deduped {c.deduped} | relevant {c.relevant} "
        f"| scored {c.scored} | unscored {c.unscored}"
        + (f" (budget {c.unscored_budget})" if c.unscored_budget else "")
        + (f" | undated {c.undated}" if c.undated else "")
    )
    if c.dedupe_unavailable:
        lines.append("dedupe: unavailable")
    if c.backlog_unavailable:
        lines.append("backlog: unavailable (novelty less reliable)")
    return "\n".join(lines)


def all_failed(results: list[SourceResult]) -> bool:
    enabled = [r for r in results if r.status != "disabled"]
    return bool(enabled) and all(r.status in ("failed", "malformed") for r in enabled)


def render_digest(
    ranked: list[Scored],
    results: list[SourceResult],
    counts: Counts,
    run_id: str,
) -> tuple[str, dict[str, Any] | None, list[str]]:
    """Return (text, reply_markup, overflow_reply_texts). text <= 4096 chars."""
    footer = render_footer(results, counts)
    if all_failed(results):
        return "Scout: all sources failed.\n\n" + footer, None, []
    if not ranked:
        return "Scout: no relevant items were found.\n\n" + footer, None, []
    blocks: list[str] = []
    for n, it in enumerate(ranked, 1):
        rel = ("adds to " if it.adds_to else "related: ") + ", ".join(it.related) if it.related else ""
        block = (
            f"{n}. <a href=\"{html.escape(it.link, quote=True)}\">{html.escape(it.title)}</a> "
            f"({html.escape(it.source)}) score {it.score:.1f} -> {html.escape(it.repo)}\n"
            f"{html.escape(it.pitch_ru)}" + (f"\n{html.escape(rel)}" if rel else "")
        )
        blocks.append(block)
    tail = "\n\n" + footer
    keep = len(blocks)
    while keep > 1 and len("\n\n".join(blocks[:keep])) + len(tail) > MAX_MESSAGE_CHARS:
        keep -= 1
    text = "\n\n".join(blocks[:keep]) + tail
    if len(text) > MAX_MESSAGE_CHARS:
        text = text[: MAX_MESSAGE_CHARS - 1] + "~"
    # Budget the keyboard only over items still in the message.
    rows, fallbacks = build_keyboard(ranked[:keep], run_id)
    overflow = [f[:MAX_MESSAGE_CHARS] for _n, f in fallbacks]
    return text, {"inline_keyboard": rows}, overflow
